export function RouteLoadingSkeleton({
  variant,
}: {
  variant: RouteSkeletonVariant;
}) {
  const name = `${variant}-page`;
  const frame = (
    <div
      className={`w-full ${heightByVariant[variant]}`}
      aria-hidden="true"
    />
  );

  return (
    <div
      role="status"
      aria-label={`Loading ${variant}`}
      className="mx-auto w-full max-w-7xl px-4 py-2 sm:px-6"
    >
      <BoneyardSkeleton
        name={name}
        loading
        initialBones={bonesByVariant[variant]}
        fixture={frame}
        fallback={frame}
        select="viewport"
        animate="pulse"
        color="#e7e7e9"
        darkColor="#27272a"
        transition={180}
        className="w-full"
      >
        {frame}
      </BoneyardSkeleton>
      <span className="sr-only">Loading…</span>
    </div>
  );
}
